#!/bin/sh
# Writes the relay script's two constants from its one source,
# Sources/HerdrKit/Resources/adari-relay.pl (docs/relay.md):
#   desktop/src/main/herdr/relay-script.ts   export const relayScript = "<the file, escaped>";
#   Sources/HerdrKit/RelayScript.swift        public enum RelayScript { public static let text = <raw string> }
# Run it after every edit of the .pl and commit what it writes. A test in each
# app (desktop relay-script.test.ts, HerdrKit RelayScriptTests) reads the .pl
# and fails when a constant differs from it by one byte.
# Usage: scripts/gen-relay-script.sh
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
exec /usr/bin/perl -e '
use strict;
use warnings;
use JSON::PP;
my ($root) = @ARGV;
my $src = "$root/Sources/HerdrKit/Resources/adari-relay.pl";
open(my $in, "<:raw", $src) or die "gen-relay-script: $src: $!\n";
my $text = do { local $/; <$in> };
close $in;
die "gen-relay-script: $src is empty\n" if $text eq "";
die "gen-relay-script: $src is not UTF-8\n" unless utf8::decode(my $check = $text);
die "gen-relay-script: $src has a carriage return (Swift would turn it into a newline)\n" if $text =~ /\r/;
die "gen-relay-script: $src does not end with a newline\n" unless $text =~ /\n\z/;

sub put {
  my ($path, $body) = @_;
  open(my $out, ">:raw", "$path.tmp") or die "gen-relay-script: $path: $!\n";
  print $out $body;
  close $out or die "gen-relay-script: $path: $!\n";
  rename("$path.tmp", $path) or die "gen-relay-script: $path: $!\n";
  print "wrote $path\n";
}

# TypeScript: one JSON string literal (ASCII, every other character escaped).
my $json = JSON::PP->new->ascii->allow_nonref->encode($check);
put("$root/desktop/src/main/herdr/relay-script.ts", <<"TS");
// GENERATED by scripts/gen-relay-script.sh from Sources/HerdrKit/Resources/adari-relay.pl: do not edit.
// The relay (speed contract v1, docs/relay.md): the Perl script the command
// connection sends along in one exec when it connects (relay.ts
// relayLaunchCommand). An empty string means relay off (every request takes
// the exec-per-request path); tests that need relay off pass "" themselves.
// relay-script.test.ts checks it equals the .pl byte for byte.

export const relayScript = $json;
TS

# Swift: a multi-line raw string literal, with enough "#" that nothing in the
# script ends it or interpolates; its last newline before the closing
# delimiter is not part of the value, so the value is the file exactly.
my $hashes = "#";
$hashes .= "#" while index($text, "\"\"\"$hashes") >= 0 || index($text, "\\$hashes") >= 0;
put("$root/Sources/HerdrKit/RelayScript.swift", <<"SWIFT");
// GENERATED by scripts/gen-relay-script.sh from Sources/HerdrKit/Resources/adari-relay.pl: do not edit.

/// The Mac-side relay script (speed contract v1, docs/relay.md) the
/// transport sends along in one exec on its command connection
/// (`CitadelTransport.relayCommand`). An empty string means relay off:
/// every request, stream and transcript read runs the exec path; tests that
/// need relay off pass "" themselves. RelayScriptTests checks it equals the
/// .pl byte for byte.
public enum RelayScript {
    public static let text = $hashes"""
$text
"""$hashes
}
SWIFT
' "$ROOT"
